#!/usr/bin/env node
/* =============================================================================
 * check-coverage.js — coverage report: map tables vs demonstrated example rows
 * =============================================================================
 *
 * PURPOSE (implements decision D-scope-1)
 *   Answers, per domain: (1) which rows of the page's mapping table are NOT
 *   demonstrated by a checked correspondence row ("in-scope, missing");
 *   (2) which CDA content in the canonical entry is not covered by any row —
 *   the "inventory" of incidental content, candidates for scope tagging,
 *   map suggestions, or removal from the source.
 *
 * INPUTS
 *   - examples-src/correspondence/CF-<domain>.yaml (rows may carry optional
 *     `scope:` uscdi3|header|incidental; file may carry `waivers:` — a list of
 *     {match, reason} marking map-table rows intentionally not demonstrated)
 *   - input/pagecontent/CF-<page>.md — the mapping table(s); first cell of
 *     each row holds the CDA path(s). Parsing is heuristic: markdown is
 *     stripped and /path-like tokens are extracted. Findings are therefore
 *     "possible gaps" for human review, not build failures.
 *   - examples-src/myra-jones-ccd.xml + the selector, for the inventory.
 *
 * OUTPUT
 *   - console summary per domain + a combined markdown report on stdout when
 *     run with --report. Always exits 0 (informational; per D-scope-1 the
 *     inventory must never block progress).
 * ========================================================================== */
const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { DOMParser } = require('@xmldom/xmldom');
const xpath = require('xpath');
const ROOT = path.resolve(__dirname, '..');
const NS = { v3: 'urn:hl7-org:v3' };
const sel = xpath.useNamespaces(NS);

/** pageFor: correspondence basename -> pagecontent file (plural quirks). */
const PAGE = { 'CF-medication':'CF-medications','CF-allergy':'CF-allergies','CF-problem':'CF-problems',
  'CF-immunization':'CF-immunizations','CF-procedure':'CF-procedures','CF-patient':'CF-patient','CF-vital':'CF-vitals' };

/** stripMd: remove links/markup from a table cell, keep path-ish text. */
const stripMd = s => s.replace(/\[([^\]]*)\]\([^)]*\)/g,'$1').replace(/<[^>]+>/g,' ').replace(/[*`]/g,'').trim();

/** cdaPaths: extract /path tokens from a (stripped) first table cell. */
function cdaPaths(cell){
  return (cell.match(/\/[\w@\[\]="' .\/:-]+/g)||[]).map(p=>p.trim()).filter(p=>p.length>2);
}

/** norm: normalize a path for loose matching (drop predicates, indices, @, leading /). */
const norm = p => p.replace(/\[[^\]]*\]/g,'').replace(/@/g,'').replace(/^\.?\/*/,'').replace(/\/+/g,'/').toLowerCase();

const files = process.argv.slice(2).length ? process.argv.slice(2)
  : fs.readdirSync(path.join(ROOT,'examples-src','corresponence').replace('corresponence','correspondence'))
      .filter(f=>f.endsWith('.yaml')).map(f=>path.join(ROOT,'examples-src','correspondence',f));
const ccd = new DOMParser().parseFromString(fs.readFileSync(path.join(ROOT,'examples-src','myra-jones-ccd.xml'),'utf8'),'text/xml');

/* ---------------- USCDI-3 checklist (PRIMARY; per D-scope-1) ----------------
 * examples-src/uscdi3-myra.csv (from CCDAtoFHIRSamples, v8-updated) is the
 * scope authority. Each correspondence row may carry `uscdi: "Class / Element"`
 * declaring which USCDI element it demonstrates. Statuses:
 *   DEMONSTRATED           — a checked row is tagged with the element
 *   IN SOURCE, NOT DEMO'D  — Myra has it; no tagged row yet (work or waiver)
 *   NOT IN SOURCE          — CSV says Myra lacks it (v8-addition candidate)
 *   DOMAIN NOT CONVERTED   — no correspondence file covers that data class yet
 * ------------------------------------------------------------------------- */
const csvLines = fs.readFileSync(path.join(ROOT,'examples-src','uscdi3-myra.csv'),'utf8').split('\n').slice(1);
const uscdi = csvLines.map(l=>{const c=l.split(',');return c.length>=3?{cls:c[0],el:c[1],found:c[2]}:null;}).filter(Boolean);
/** data classes with at least one converted correspondence file */
const CONVERTED = new Set(['Allergies and Intolerances','Medications','Problems','Immunizations','Procedures','Patient Demographics/Information','Vital Signs','Provenance']);
const tagIndex = {}; // "Class / Element" -> [file:rowpath]
let out = ['# Coverage report (generated by scripts/check-coverage.js)','',
  '## USCDI v3 checklist (primary scope; source: examples-src/uscdi3-myra.csv)','',
  '| Data Class | Element | In Myra | Status |','|---|---|---|---|'];

// pass 1: collect uscdi tags from all correspondence files
for (const cf of files){
  const c = yaml.load(fs.readFileSync(cf,'utf8'));
  for (const r of c.rows||[]) if (r.uscdi) (tagIndex[r.uscdi] ||= []).push(path.basename(cf).replace(/\.ya?ml$/,'')+': '+r.cda);
}
for (const u of uscdi){
  const key = u.cls+' / '+u.el;
  let status;
  if (tagIndex[key]) status = 'DEMONSTRATED ('+tagIndex[key][0]+')';
  else if (!CONVERTED.has(u.cls)) status = 'domain not yet converted';
  else if (!/yes/i.test(u.found||'')) status = 'NOT IN SOURCE (v8-addition candidate)';
  else status = '**IN SOURCE, NOT DEMONSTRATED**';
  out.push('| '+u.cls+' | '+u.el+' | '+(u.found||'No')+' | '+status+' |');
}
const counts = {demo:0, missing:0, notsrc:0, later:0};
for (const u of uscdi){
  const key=u.cls+' / '+u.el;
  if (tagIndex[key]) counts.demo++;
  else if (!CONVERTED.has(u.cls)) counts.later++;
  else if (!/yes/i.test(u.found||'')) counts.notsrc++;
  else counts.missing++;
}
console.log('USCDI-3: '+counts.demo+' demonstrated | '+counts.missing+' in-source-not-demonstrated | '+counts.notsrc+' not-in-source | '+counts.later+' awaiting domain conversion');
out.push('','Summary: '+counts.demo+' demonstrated, '+counts.missing+' in source but not demonstrated, '+counts.notsrc+' not in source, '+counts.later+' awaiting domain conversion.','',
  '## Secondary: per-domain detail (heuristic; review fodder, not verdicts)','');

const SHOW_INVENTORY = process.argv.includes('--inventory');
for (const cf of files){
  const name = path.basename(cf).replace(/\.ya?ml$/,'');
  const corr = yaml.load(fs.readFileSync(cf,'utf8'));
  const page = PAGE[name]; if(!page) continue;
  const md = fs.readFileSync(path.join(ROOT,'input','pagecontent',page+'.md'),'utf8');
  // --- bucket 1: map-table rows vs correspondence rows ---
  const corrNorms = corr.rows.map(r=>norm(r.cda));
  const waivers = (corr.waivers||[]);
  const missing = [];
  for (const line of md.split('\n')){
    if(!/^\|/.test(line)) continue;
    const cells = line.split('|').map(stripMd);
    if(cells.length<3 || /^[:\- ]*$/.test(cells[1])) continue;
    for (const p of cdaPaths(cells[1])){
      const n = norm(p);
      if(!n) continue;
      const demonstrated = corrNorms.some(c=>c.includes(n)||n.includes(c));
      const waived = waivers.find(w=>n.includes(norm(w.match)));
      if(!demonstrated && !waived) missing.push(p);
    }
  }
  // --- bucket 2: inventory of un-marked CDA content in the canonical entry ---
  let entry;
  if (corr.selector.headerPath){
    entry = sel('//'+corr.selector.headerPath.replace(/(^|\/)/g,'$1v3:'),ccd)[0];
  } else {
    const section = sel(`//v3:section[v3:code/@code="${corr.selector.section}"]`,ccd)[0];
    entry = section && sel(`.//v3:${corr.selector.element}[v3:id/@root="${corr.selector.entryId}"]`,section)[0];
  }
  const covered = new Set();
  for (const r of corr.rows){
    const nx = r.cda.replace(/(^|\/|\[)(?!@)([A-Za-z_][\w-]*)(?=[\/\[@=\]]|$)/g,(m,pre,el)=>['and','or','not'].includes(el)?m:`${pre}v3:${el}`);
    try { sel(nx,entry).forEach(nd=>covered.add(nd)); } catch(e){}
  }
  const inv=[];
  (function walk(el,pathStr){
    for(const a of Array.from(el.attributes||[]))
      if(!a.name.startsWith('xmlns') && !covered.has(a) && !['classCode','moodCode','typeCode','root','extension','xsi:type','nullFlavor','inversionInd','operator','use','qualifier','contextConductionInd'].includes(a.name) && a.name!=='codeSystemName')
        inv.push(`${pathStr}/@${a.name}="${a.value.slice(0,40)}"`);
    for(const k of Array.from(el.childNodes||[])) if(k.nodeType===1) walk(k,pathStr+'/'+k.nodeName.replace('v3:',''));
  })(entry, corr.selector.element||'patientRole');
  const demonstrated = corr.rows.length;
  console.log(`${name}: ${demonstrated} demonstrated | ${missing.length} possible map-table gaps | ${inv.length} undemonstrated CDA values`);
  out.push(`### ${name}`,'',`Demonstrated rows: ${demonstrated}. Waivers: ${waivers.length}. Map-table gap candidates: ${missing.length}. Undemonstrated values: ${inv.length}${SHOW_INVENTORY?'':' (run with --inventory to list)'}.`,'',
    ...(missing.length?['Map-table gap candidates:',...missing.map(m=>`- \`${m}\``),'']:[]),
    ...(SHOW_INVENTORY&&inv.length?['Inventory:',...inv.slice(0,60).map(m=>`- \`${m}\``),'']:[]));
}
if (process.argv.includes('--report')) {} // reserved
fs.writeFileSync(path.join(ROOT,'coverage-report.md'), out.join('\n'));
console.log('report -> coverage-report.md');
